#!/usr/bin/env bash
set -euo pipefail
cd "$(dirname "$0")/.."
golangci-lint run --config .golangci.yml ./...
export GOFLAGS="${GOFLAGS:-} -tags=integration"
contractcheck ./...
nilaway -include-pkgs="$(go list -m)" -pretty-print=false -experimental-struct-init ./...
(
  cd tools
  go vet -mod=readonly ./...
  go test -mod=readonly -count=1 ./...
  golangci-lint run --config ../.golangci.yml ./...
)
